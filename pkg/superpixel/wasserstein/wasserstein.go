// Priority queue for merge candidates (min-heap by kappa)

type mergeCandidate struct {
	i, j  int
	kappa float64
	cost  float64
}

func mergeCandidateComparator(a, b mergeCandidate) int {
	switch {
	case a.kappa < b.kappa:
		return -1
	case a.kappa > b.kappa:
		return 1
	default:
		return 0
	}
}

// ---------------------------------------------------------------------------
// Region bookkeeping
// ---------------------------------------------------------------------------

type region struct {
	active        bool
	pixelCount    int
	hist          []float64
	heterogeneity float64
	neighbors     map[int]struct{}
}

// ---------------------------------------------------------------------------
// Sinkhorn solver for entropic OT
// ---------------------------------------------------------------------------

type otSolver struct {
	k          int
	cost       [][]float64
	kernel     [][]float64
	epsilon    float64
	iterations int
}

func newOtSolver(centers [][3]float64, epsilon float64, iterations int) *otSolver {
	k := len(centers)
	cost := make([][]float64, k)
	maxCost := 0.0
	for i := 0; i < k; i++ {
		cost[i] = make([]float64, k)
		for j := 0; j < k; j++ {
			dl := centers[i][0] - centers[j][0]
			da := centers[i][1] - centers[j][1]
			db := centers[i][2] - centers[j][2]
			d := dl*dl + da*da + db*db
			cost[i][j] = d
			if d > maxCost {
				maxCost = d
			}
		}
	}
	if maxCost <= 0 {
		maxCost = 1
	}
	for i := 0; i < k; i++ {
		for j := 0; j < k; j++ {
			cost[i][j] = cost[i][j] / maxCost
		}
	}
	kernel := make([][]float64, k)
	for i := 0; i < k; i++ {
		kernel[i] = make([]float64, k)
		for j := 0; j < k; j++ {
			kernel[i][j] = math.Exp(-cost[i][j] / epsilon)
		}
	}
	return &otSolver{k: k, cost: cost, kernel: kernel, epsilon: epsilon, iterations: iterations}
}

func (s *otSolver) distance(a, b []float64) float64 {
	k := s.k
	u := make([]float64, k)
	v := make([]float64, k)
	for i := 0; i < k; i++ {
		u[i] = 1
		v[i] = 1
	}

	const tiny = 1e-12
	for iter := 0; iter < s.iterations; iter++ {
		for i := 0; i < k; i++ {
			den := 0.0
			for j := 0; j < k; j++ {
				den += s.kernel[i][j] * v[j]
			}
			if den < tiny {
				den = tiny
			}
			u[i] = a[i] / den
		}
		for j := 0; j < k; j++ {
			den := 0.0
			for i := 0; i < k; i++ {
				den += s.kernel[i][j] * u[i]
			}
			if den < tiny {
				den = tiny
			}
			v[j] = b[j] / den
		}
	}

	cost := 0.0
	for i := 0; i < k; i++ {
		for j := 0; j < k; j++ {
			cost += u[i] * s.kernel[i][j] * v[j] * s.cost[i][j]
		}
	}
	return cost
}

// ---------------------------------------------------------------------------
// Disjoint set for final labeling
// ---------------------------------------------------------------------------

type dsu struct {
	parent []int
}

func newDsu(n int) *dsu {
	p := make([]int, n)
	for i := range p {
		p[i] = i
	}
	return &dsu{parent: p}
}

func (d *dsu) find(x int) int {
	if d.parent[x] != x {
		d.parent[x] = d.find(d.parent[x])
	}
	return d.parent[x]
}

func (d *dsu) union(into, from int) {
	d.parent[from] = into
}

// ---------------------------------------------------------------------------
// Representative colours / region merging
// ---------------------------------------------------------------------------

func computeRepresentativeColors(labCache [][3]float64, k int) [][3]float64 {
	if k < 1 {
		k = 1
	}
	total := len(labCache)
	maxSamples := 10000
	step := 1
	if total > maxSamples {
		step = int(math.Ceil(float64(total) / float64(maxSamples)))
	}
	samples := make([][3]float64, 0, total/step+1)
	for i := 0; i < total; i += step {
		samples = append(samples, labCache[i])
	}
	if len(samples) == 0 {
		return make([][3]float64, k)
	}

	centers := make([][3]float64, k)
	for i := 0; i < k; i++ {
		centers[i] = samples[(i*len(samples))/k]
	}

	maxIter := 10
	for iter := 0; iter < maxIter; iter++ {
		sums := make([][3]float64, k)
		counts := make([]int, k)
		for _, s := range samples {
			nearest := 0
			minDist := math.Inf(1)
			for c := 0; c < k; c++ {
				dl := s[0] - centers[c][0]
				da := s[1] - centers[c][1]
				db := s[2] - centers[c][2]
				d := dl*dl + da*da + db*db
				if d < minDist {
					minDist = d
					nearest = c
				}
			}
			sums[nearest][0] += s[0]
			sums[nearest][1] += s[1]
			sums[nearest][2] += s[2]
			counts[nearest]++
		}

		shift := 0.0
		for c := 0; c < k; c++ {
			if counts[c] == 0 {
				centers[c] = samples[(c+iter)%len(samples)]
				continue
			}
			newCenter := [3]float64{
				sums[c][0] / float64(counts[c]),
				sums[c][1] / float64(counts[c]),
				sums[c][2] / float64(counts[c]),
			}
			dl := newCenter[0] - centers[c][0]
			da := newCenter[1] - centers[c][1]
			db := newCenter[2] - centers[c][2]
			shift += dl*dl + da*da + db*db
			centers[c] = newCenter
		}
		if shift < 1e-4 {
			break
		}
	}

	return centers
}

func Run(img image.Image, initialSuperpixels int, targetRegions int, compactness float64, slicIterations int, initialPerturbationNeighborhoodRadius int, histogramBins int, sinkhornEpsilon float64, sinkhornIterations int) (superpixel.SpResult, error) {
	if img == nil {
		return superpixel.SpResult{}, errors.New("Image is nil.")
	}
	if targetRegions < 1 {
		return superpixel.SpResult{}, errors.New("Target region count must be at least 1.")
	}
	if histogramBins < 2 {
		return superpixel.SpResult{}, errors.New("Histogram bins must be at least 2.")
	}
	if sinkhornEpsilon <= 0 {
		return superpixel.SpResult{}, errors.New("Sinkhorn epsilon must be positive.")
	}
	if sinkhornIterations < 1 {
		return superpixel.SpResult{}, errors.New("Sinkhorn iterations must be at least 1.")
	}

	// Initial superpixels via SLIC
	initialResult, err := slic.Run(img, initialSuperpixels, compactness, initialPerturbationNeighborhoodRadius, slicIterations)
	if err != nil {
		return superpixel.SpResult{}, err
	}

	width := img.Bounds().Dx()
	height := img.Bounds().Dy()
	total := width * height

	labelMapInt := make([]int, total)
	for y := 0; y < height; y++ {
		for x := 0; x < width; x++ {
			labelMapInt[y*width+x] = int(initialResult.LabelMap.Gray16At(x, y).Y)
		}
	}
	m := initialResult.SpCount
	if targetRegions > m {
		return superpixel.SpResult{}, errors.New("Target region count can not exceed initial superpixel count.")
	}

	// LAB cache
	var labCache [][3]float64
	superpixel_utils.BuildLabCache(img, &labCache)

	// Representative colors for histograms
	centers := computeRepresentativeColors(labCache, histogramBins)
	ot := newOtSolver(centers, sinkhornEpsilon, sinkhornIterations)

	// Bin index for each pixel
	binIndex := make([]int, total)
	for idx, lab := range labCache {
		minIdx := 0
		minDist := math.Inf(1)
		for c := 0; c < len(centers); c++ {
			dl := lab[0] - centers[c][0]
			da := lab[1] - centers[c][1]
			db := lab[2] - centers[c][2]
			d := dl*dl + da*da + db*db
			if d < minDist {
				minDist = d
				minIdx = c
			}
		}
		binIndex[idx] = minIdx
	}

	// Region histograms
	regions := make([]region, m)
	for i := 0; i < m; i++ {
		regions[i] = region{
			active:    true,
			hist:      make([]float64, histogramBins),
			neighbors: make(map[int]struct{}),
		}
	}

	for idx := 0; idx < total; idx++ {
		lbl := labelMapInt[idx]
		regions[lbl].pixelCount++
		regions[lbl].hist[binIndex[idx]]++
	}
	for i := 0; i < m; i++ {
		if regions[i].pixelCount == 0 {
			continue
		}
		count := float64(regions[i].pixelCount)
		for b := 0; b < histogramBins; b++ {
			regions[i].hist[b] /= count
		}
	}

	// Build adjacency
	addEdge := func(a, b int) {
		if a == b {
			return
		}
		regions[a].neighbors[b] = struct{}{}
		regions[b].neighbors[a] = struct{}{}
	}
	for y := 0; y < height; y++ {
		for x := 0; x < width; x++ {
			idx := y*width + x
			lbl := labelMapInt[idx]
			if x+1 < width {
				right := labelMapInt[idx+1]
				if right != lbl {
					addEdge(lbl, right)
				}
			}
			if y+1 < height {
				down := labelMapInt[idx+width]
				if down != lbl {
					addEdge(lbl, down)
				}
			}
		}
	}

	// Merge loop ---------------------------------------------------------
	pq := priorityqueue.NewWith(mergeCandidateComparator)

	for i := 0; i < m; i++ {
		for j := range regions[i].neighbors {
			if j <= i {
				continue
			}
			cost := ot.distance(regions[i].hist, regions[j].hist)
			kappa := cost - regions[i].heterogeneity - regions[j].heterogeneity
			pq.Enqueue(mergeCandidate{i: i, j: j, kappa: kappa, cost: cost})
		}
	}

	dsu := newDsu(m)
	activeCount := m

	for activeCount > targetRegions && !pq.Empty() {
		item, _ := pq.Dequeue()
		i := item.i
		j := item.j
		if !regions[i].active || !regions[j].active {
			continue
		}
		if _, ok := regions[i].neighbors[j]; !ok {
			continue
		}
		currentCost := ot.distance(regions[i].hist, regions[j].hist)
		currentKappa := currentCost - regions[i].heterogeneity - regions[j].heterogeneity
		if currentKappa > item.kappa+1e-9 {
			pq.Enqueue(mergeCandidate{i: i, j: j, kappa: currentKappa, cost: currentCost})
			continue
		}

		// Merge j into i
		regions[i].heterogeneity = currentCost
		countI := regions[i].pixelCount
		countJ := regions[j].pixelCount
		regions[i].pixelCount = countI + countJ
		if regions[i].pixelCount > 0 {
			fCountI := float64(countI)
			fCountJ := float64(countJ)
			for b := 0; b < histogramBins; b++ {
				regions[i].hist[b] = (regions[i].hist[b]*fCountI + regions[j].hist[b]*fCountJ) / (fCountI + fCountJ)
			}
		}
		regions[j].active = false
		dsu.union(i, j)
		activeCount--

		delete(regions[i].neighbors, j)
		for k := range regions[j].neighbors {
			if !regions[k].active || k == i {
				delete(regions[k].neighbors, j)
				continue
			}
			delete(regions[k].neighbors, j)
			regions[k].neighbors[i] = struct{}{}
			regions[i].neighbors[k] = struct{}{}
		}
		regions[j].neighbors = nil

		for k := range regions[i].neighbors {
			if !regions[k].active {
				delete(regions[i].neighbors, k)
				continue
			}
			cost := ot.distance(regions[i].hist, regions[k].hist)
			kappa := cost - regions[i].heterogeneity - regions[k].heterogeneity
			pq.Enqueue(mergeCandidate{i: i, j: k, kappa: kappa, cost: cost})
		}
	}

	// Build final label map ----------------------------------------------
	labelMap := image.NewGray16(image.Rect(0, 0, width, height))
	rootToLabel := make(map[int]int)
	nextLabel := 0
	for y := 0; y < height; y++ {
		for x := 0; x < width; x++ {
			idx := y*width + x
			root := dsu.find(labelMapInt[idx])
			label, ok := rootToLabel[root]
			if !ok {
				label = nextLabel
				rootToLabel[root] = label
				nextLabel++
			}
			labelMap.SetGray16(x, y, color.Gray16{Y: uint16(label)})
		}
	}

	return superpixel.MakeSpResult(labelMap), nil
}
